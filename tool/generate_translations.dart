// Generates assets/i18n/*.json and lib/src/data/translation_locales.dart from
// the Unicode CLDR country names.
//
// Usage:
//   1. Download and extract the CLDR locale names, e.g.
//        curl -LO https://registry.npmjs.org/cldr-localenames-full/-/cldr-localenames-full-48.2.0.tgz
//        mkdir cldr && tar -xzf cldr-localenames-full-48.2.0.tgz -C cldr
//   2. dart run tool/generate_translations.dart cldr/package
//
// A language is included when CLDR names at least [minCoverage] of the bundled
// countries; countries it doesn't name fall back to English at runtime.
// A regional or script variant (e.g. pt-PT, zh-Hant, sr-Latn) is included when
// it differs from every already-included locale of the same language on at
// least [minVariantDifferences] country names.

import 'dart:convert';
import 'dart:io';

const double minCoverage = 0.75;
const int minVariantDifferences = 5;

/// Variants processed first, so related regions are deduplicated against the
/// locale apps are most likely to ask for (e.g. pt-AO folds into pt-PT).
const List<String> preferredVariants = <String>[
  'zh-Hant',
  'zh-Hant-HK',
  'sr-Latn',
  'pt-PT',
  'es-419',
  'en-001',
  'en-GB',
  'fr-CA',
];

/// Historic or specialist orthographies not worth shipping.
const Set<String> excludedVariants = <String>{'en-Dsrt', 'el-polyton'};

const String outputDir = 'assets/i18n';
const String localesFile = 'lib/src/data/translation_locales.dart';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/generate_translations.dart <cldr package dir>',
    );
    exit(64);
  }
  final Directory cldr = Directory(args.single);
  final Directory main = Directory('${cldr.path}/main');
  final Map<String, dynamic> packageJson =
      jsonDecode(File('${cldr.path}/package.json').readAsStringSync())
          as Map<String, dynamic>;
  final String version = packageJson['version'] as String;

  final List<String> countryCodes =
      RegExp(r"code: '(\w+)'")
          .allMatches(File('lib/src/data/countries.dart').readAsStringSync())
          .map((RegExpMatch m) => m.group(1)!)
          .toList();

  final List<String> locales =
      main
          .listSync()
          .whereType<Directory>()
          .map(
            (Directory d) =>
                d.uri.pathSegments.lastWhere((String s) => s.isNotEmpty),
          )
          .toList()
        ..sort();

  final Map<String, Map<String, String>> names = <String, Map<String, String>>{
    for (final String locale in locales) locale: _territories(main, locale),
  };

  int coverage(String locale) =>
      countryCodes.where((String c) => names[locale]!.containsKey(c)).length;
  final int needed = (countryCodes.length * minCoverage).ceil();

  final Map<String, Map<String, String>> included =
      <String, Map<String, String>>{
        for (final String locale in locales)
          if (!locale.contains('-') && coverage(locale) >= needed)
            locale: names[locale]!,
      };

  final List<String> variants = <String>[
    ...preferredVariants.where(names.containsKey),
    ...locales.where(
      (String l) =>
          l.contains('-') &&
          !preferredVariants.contains(l) &&
          !excludedVariants.contains(l),
    ),
  ];
  for (final String variant in variants) {
    final String language = variant.split('-').first;
    if (!included.containsKey(language) || coverage(variant) < needed) {
      continue;
    }
    final Map<String, String> variantNames = names[variant]!;
    final int minDifferences = included.keys
        .where((String l) => l == language || l.startsWith('$language-'))
        .map(
          (String l) =>
              countryCodes
                  .where((String c) => variantNames[c] != included[l]![c])
                  .length,
        )
        .reduce((int a, int b) => a < b ? a : b);
    if (minDifferences >= minVariantDifferences) {
      included[variant] = variantNames;
    }
  }

  final Directory out = Directory(outputDir);
  for (final FileSystemEntity f in out.listSync()) {
    if (f.path.endsWith('.json')) {
      f.deleteSync();
    }
  }
  const JsonEncoder encoder = JsonEncoder.withIndent('    ');
  final List<String> ids = included.keys.map(_toId).toList()..sort();
  for (final MapEntry<String, Map<String, String>> e in included.entries) {
    File(
      '$outputDir/${_toId(e.key)}.json',
    ).writeAsStringSync('${encoder.convert(e.value)}\n');
  }
  File(
    '$outputDir/LICENSE',
  ).writeAsStringSync(File('${cldr.path}/LICENSE').readAsStringSync());

  File(localesFile).writeAsStringSync('''
// GENERATED by tool/generate_translations.dart from CLDR $version.
// Do not edit by hand.

/// The translation files bundled in assets/i18n/, as `language`,
/// `language_Script`, `language_REGION` or `language_Script_REGION`.
const Set<String> kTranslationLocales = <String>{
${ids.map((String id) => "  '$id',").join('\n')}
};
''');

  final int languages = ids.where((String id) => !id.contains('_')).length;
  stdout.writeln(
    'CLDR $version: wrote ${ids.length} files '
    '($languages languages, ${ids.length - languages} variants).',
  );
}

/// Country names for [locale], keyed by two-letter region code.
Map<String, String> _territories(Directory main, String locale) {
  final Map<String, dynamic> json =
      jsonDecode(
            File('${main.path}/$locale/territories.json').readAsStringSync(),
          )
          as Map<String, dynamic>;
  final Map<String, dynamic> territories =
      ((json['main'] as Map<String, dynamic>)[locale]
              as Map<String, dynamic>)['localeDisplayNames']
          as Map<String, dynamic>;
  final Map<String, dynamic> byCode =
      territories['territories'] as Map<String, dynamic>;
  return <String, String>{
    for (final MapEntry<String, dynamic> e in byCode.entries)
      if (RegExp(r'^[A-Z]{2}$').hasMatch(e.key)) e.key: e.value as String,
  };
}

/// `zh-Hant-HK` -> `zh_Hant_HK`, matching how the loader builds file names.
String _toId(String cldrLocale) => cldrLocale.replaceAll('-', '_');
