// Generates lib/src/data/phone_lengths.dart: the mobile phone number lengths
// of every bundled country, taken from dlibphonenumber's metadata.
//
// Storing them lets Country.phoneNumberLength work without libphonenumber,
// so apps that never validate numbers don't include its ~2 MB of metadata.
//
// Usage, after upgrading dlibphonenumber or editing countries.dart:
//   dart run tool/generate_phone_lengths.dart
//
// The test "stored phone lengths match dlibphonenumber" fails when the file
// is out of date.

import 'dart:io';

import 'package:country_code_selector/src/services/phone_number_length_service.dart';

const String countriesFile = 'lib/src/data/countries.dart';
const String outputFile = 'lib/src/data/phone_lengths.dart';

void main() {
  final String source = File(countriesFile).readAsStringSync();
  // Each entry lists its code, then its dial codes; the first is the main one.
  final Iterable<RegExpMatch> entries = RegExp(
    r"code: '(\w+)',[\s\S]*?dialCodes: <String>\['([^']+)'",
  ).allMatches(source);

  final List<String> lines = <String>[];
  final List<String> unknown = <String>[];
  for (final RegExpMatch m in entries) {
    final String code = m.group(1)!;
    final List<int>? lengths =
        PhoneNumberLengthService.lengthsFor(code, dialCode: m.group(2));
    if (lengths == null) {
      unknown.add(code);
    } else {
      lines.add("  '$code': <int>[${lengths.join(', ')}],");
    }
  }

  lines.sort();
  unknown.sort();
  File(outputFile).writeAsStringSync('''
// GENERATED by tool/generate_phone_lengths.dart from dlibphonenumber
// ${_dlibphonenumberVersion()}. Do not edit by hand.

/// Mobile phone number lengths of the bundled countries: the digits after the
/// country's dial code, without the national trunk prefix. Countries without
/// libphonenumber metadata (${unknown.join(', ')}) are absent.
const Map<String, List<int>> kPhoneNumberLengths = <String, List<int>>{
${lines.join('\n')}
};
''');
  stdout.writeln('Wrote ${lines.length} countries to $outputFile '
      '(no metadata: ${unknown.join(', ')}).');
}

String _dlibphonenumberVersion() {
  final File lock = File('pubspec.lock');
  if (!lock.existsSync()) {
    return '(unknown version)';
  }
  final RegExpMatch? m = RegExp(
    r'dlibphonenumber:[\s\S]*?version: "([^"]+)"',
  ).firstMatch(lock.readAsStringSync());
  return m == null ? '(unknown version)' : m.group(1)!;
}
