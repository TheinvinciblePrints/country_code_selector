"""Generates lib/src/data/text_folding_table.dart.

The table maps characters to their search-folded form: accents and other
combining marks removed (é -> e, ё -> е, إ -> ا), plus a few letters with no
Unicode decomposition (ß -> ss, ø -> o, ة -> ه, ى -> ي). Dart has no built-in
Unicode normalization, so the table is generated once from Python's Unicode
database and committed.

Only scripts where removing marks keeps words recognisable are covered: Latin,
Greek, Cyrillic, Hebrew and Arabic. Scripts such as Devanagari or Thai use
marks for vowels, so folding them would merge different words.

Usage (any Python 3):
    python3 tool/generate_text_folding.py
"""

import unicodedata

OUTPUT = 'lib/src/data/text_folding_table.dart'

RANGES = [
    (0x00C0, 0x024F),  # Latin-1 Supplement letters, Latin Extended-A/B
    (0x0300, 0x036F),  # Combining diacritical marks
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x04FF),  # Cyrillic
    (0x0590, 0x05FF),  # Hebrew (niqqud, cantillation)
    (0x0600, 0x06FF),  # Arabic (hamza forms, tashkeel)
    (0x1E00, 0x1EFF),  # Latin Extended Additional (Vietnamese)
    (0x1F00, 0x1FFF),  # Greek Extended
]

# Letters that don't decompose but are commonly typed as plain letters.
EXTRA = {
    'ß': 'ss', 'æ': 'ae', 'œ': 'oe', 'ø': 'o', 'ł': 'l', 'đ': 'd',
    'ð': 'd', 'þ': 'th', 'ı': 'i', 'ħ': 'h', 'ŧ': 't', 'ŋ': 'n',
    # Arabic: taa marbuta and alif maqsura are routinely typed as haa/yaa;
    # Persian yeh and keheh are matched with their Arabic counterparts.
    'ة': 'ه', 'ى': 'ي', 'ی': 'ي', 'ک': 'ك',
    # Arabic tatweel (kashida) is decorative.
    'ـ': '',
}


def fold(ch):
    if ch in EXTRA:
        return EXTRA[ch]
    decomposed = unicodedata.normalize('NFD', ch)
    out = ''.join(c for c in decomposed if unicodedata.category(c) != 'Mn')
    return ''.join(EXTRA.get(c, c) for c in out)


entries = {}
for lo, hi in RANGES:
    for cp in range(lo, hi + 1):
        ch = chr(cp)
        # Keys are lowercase: the Dart side lowercases before looking up.
        if not unicodedata.category(ch).startswith(('L', 'M')):
            continue
        if ch.lower() != ch:
            continue
        folded = fold(ch)
        if folded != ch:
            entries[cp] = folded


def dart_string(s):
    return "'" + ''.join(
        c if c.isalnum() and ord(c) < 128 else f'\\u{{{ord(c):x}}}' for c in s
    ) + "'"


lines = [f'  0x{cp:04x}: {dart_string(v)},' for cp, v in sorted(entries.items())]
with open(OUTPUT, 'w') as f:
    f.write(
        '// GENERATED by tool/generate_text_folding.py from Unicode data. Do not\n'
        '// edit by hand.\n\n'
        '/// Maps lowercase characters to their search-folded form: accents and\n'
        '/// other combining marks removed, and a few letters replaced with how\n'
        '/// people usually type them. Used by `foldForSearch`.\n'
        'const Map<int, String> kTextFoldingTable = <int, String>{\n'
        + '\n'.join(lines)
        + '\n};\n'
    )
print(f'Wrote {len(entries)} entries to {OUTPUT}')
